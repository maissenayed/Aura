// Fallback generator for unmapped muscle IDs
export function getMuscleInfo(muscleId: string | null): MuscleMetadata | null {
  if (!muscleId) return null;
  if (MUSCLE_DICTIONARY[muscleId]) {
    return MUSCLE_DICTIONARY[muscleId];
  }

  // Generate clean fallback based on ID string formatting
  const cleanName = muscleId
    .replace(/-/g, ' ')
    .replace(/\b\w/g, l => l.toUpperCase());

  return {
    id: muscleId,
    baseGroup: muscleId.split('-')[0] || 'muscle',
    name: cleanName,
    latinName: `Musculus ${cleanName}`,
    category: 'Push',
    region: 'Upper Body',
    description: `Targeted muscle group (${cleanName}) involved in calisthenics stabilization and kinetic chain transfers.`,
    primaryFunction: 'Stabilization and movement control.',
    origin: 'Anatomical muscle attachment point.',
    insertion: 'Distal tendon insertion site.',
    exerciseIds: ['ex_1', 'ex_2', 'ex_101'],
    formTip: 'Focus on full range of motion, strict tension, and deliberate breathing.',
  };
}

// Get all matching exercises for a muscle ID, sorted by level ascending, with min/max level filter
export function getExercisesForMuscle(
  muscleId: string,
  minLevel: number = 1,
  maxLevel: number = 20
): Exercise[] {
  const info = getMuscleInfo(muscleId);
  if (!info) return [];

  const explicitIds = new Set(info.exerciseIds || []);
  const baseGroup = info.baseGroup.toLowerCase();

  const matched = EXERCISES.filter((ex) => {
    // 1. Explicit ID match
    if (explicitIds.has(ex.id)) return true;

    // 2. Swimlane + Category / SubCategory / Name keyword match
    if (ex.swimlane === info.category) {
      const name = ex.name.toLowerCase();
      const sub = ex.subCategory.toLowerCase();

      if (baseGroup === 'chest' && (sub.includes('pushup') || sub.includes('dip') || name.includes('push') || name.includes('dip'))) return true;
      if (baseGroup === 'biceps' && (sub.includes('pull-up') || sub.includes('chin') || sub.includes('curl') || name.includes('chin'))) return true;
      if (baseGroup === 'triceps' && (sub.includes('dip') || sub.includes('pushup') || sub.includes('handstand') || name.includes('extension'))) return true;
      if (baseGroup === 'shoulders' && (sub.includes('handstand') || sub.includes('planche') || sub.includes('pike') || name.includes('press'))) return true;
      if (baseGroup === 'lats' && (sub.includes('pull-up') || sub.includes('pullup') || sub.includes('row') || sub.includes('lever'))) return true;
      if (baseGroup === 'traps' && (sub.includes('row') || sub.includes('shrug') || sub.includes('pull-up'))) return true;
      if (baseGroup === 'abs' && (sub.includes('l-sit') || sub.includes('v-sit') || sub.includes('leg raise') || sub.includes('abs') || sub.includes('core'))) return true;
      if (baseGroup === 'obliques' && (sub.includes('flag') || sub.includes('side') || sub.includes('twist'))) return true;
      if (baseGroup === 'serratus' && (sub.includes('pushup') || sub.includes('planche') || sub.includes('scap'))) return true;
      if (baseGroup === 'quads' && (sub.includes('squat') || sub.includes('pistol') || sub.includes('lunge'))) return true;
      if (baseGroup === 'glutes' && (sub.includes('squat') || sub.includes('bridge') || sub.includes('hip') || sub.includes('lunge'))) return true;
      if (baseGroup === 'hamstrings' && (sub.includes('nordic') || sub.includes('curl') || sub.includes('bridge'))) return true;
      if (baseGroup === 'calves' && (sub.includes('calf') || sub.includes('raise') || sub.includes('jump'))) return true;
    }

    return false;
  });

  const pool = matched.length > 0 ? matched : EXERCISES.filter((ex) => ex.swimlane === info.category);

  // Sort by level ascending (easiest/lowest level first!)
  const sorted = [...pool].sort((a, b) => a.level - b.level);

  // Filter within level range
  return sorted.filter((ex) => ex.level >= minLevel && ex.level <= maxLevel);
}
