import { CatalogSkill, LevelBand, Rank, TreeRules } from '../utils/skillTree';

/**
 * The gym (lifting) skill tree: free weights, cables and machines, placed on
 * five strength levels from Novice to Elite.
 *
 * Standards are written as multiples of your bodyweight (BW), so they scale
 * with the lifter; they are guides for an adult lifter, not competition
 * standards. `level` runs 1 (Novice) to 5 (Elite) and `levelLabel` names it.
 *
 * Ids are permanent. The exercises the campaign already uses keep its ids
 * (`bench_press`, `deadlift`, …); every other skill starts with `gym_`.
 */

export const GYM_LANES = ['Push', 'Pull', 'Legs', 'Core'] as const;
export type GymLane = (typeof GYM_LANES)[number];

export const GYM_LEVELS = ['Novice', 'Beginner', 'Intermediate', 'Advanced', 'Elite'] as const;
const LEVEL_TAGS = ['NOV', 'BEG', 'INT', 'ADV', 'ELITE'];

/** "Novice" … "Elite" for levels 1–5. */
export function gymLevelName(level: number): string {
  return GYM_LEVELS[Math.max(1, Math.min(GYM_LEVELS.length, level)) - 1];
}

export function gymLevelTag(level: number): string {
  return LEVEL_TAGS[Math.max(1, Math.min(LEVEL_TAGS.length, level)) - 1];
}

const BANDS: LevelBand[] = [
  { id: 'foundation', label: 'Novice & Beginner', min: 1, max: 2 },
  { id: 'intermediate', label: 'Intermediate', min: 3, max: 3 },
  { id: 'advanced', label: 'Advanced & Elite', min: 4, max: 5 },
  { id: 'all', label: 'All levels', min: 1, max: 5 },
];

const RANKS: Rank[] = [
  { min: 0, title: 'Fresh Lifter' },
  { min: 5, title: 'Gym Regular' },
  { min: 14, title: 'Iron Disciple' },
  { min: 26, title: 'Plate Stacker' },
  { min: 38, title: 'Strength Legend' },
];

export const GYM_RULES: TreeRules = { lanes: [...GYM_LANES], bands: BANDS, ranks: RANKS };

export interface GymSkill extends CatalogSkill {
  lane: GymLane;
  /** "Novice" … "Elite". */
  tier: (typeof GYM_LEVELS)[number];
}

interface SkillInput {
  id: string;
  name: string;
  level: 1 | 2 | 3 | 4 | 5;
  lane: GymLane;
  line: string;
  after?: string[];
  focus: string;
  summary: string;
  masteredWhen: string;
  steps: string[];
  tip?: string;
  trains: string[];
}

const skill = (input: SkillInput): GymSkill => ({
  id: input.id,
  name: input.name,
  level: input.level,
  tier: GYM_LEVELS[input.level - 1],
  levelLabel: GYM_LEVELS[input.level - 1],
  lane: input.lane,
  focus: input.focus,
  subCategory: input.line,
  swimlane: input.lane,
  prerequisites: input.after ?? [],
  summary: input.summary,
  unlockRequirements: input.masteredWhen,
  description: input.steps,
  expertTip: input.tip,
  musclesTargeted: input.trains,
  youtubeQuery: `${input.name} proper form`,
  xpReward: input.level * 200,
});

