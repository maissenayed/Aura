import type { TrainableAttribute } from '../utils/campaignPlan';
import { CatalogSkill, LevelBand, Rank, TreeRules, listOf } from '../utils/skillTree';

/**
 * The yoga skill tree: standing poses, forward folds, hip openers, twists,
 * backbends, arm balances and inversions, each placed on the level where
 * people usually learn it.
 *
 * Every pose is held, so every standard is a hold time written first
 * ("30 s each side, …"): the skill test reads it as a count in seconds and
 * offers the hold timer, and a logged hold of that length is a pass, as it is
 * for a calisthenics hold. Prerequisites point at easier poses. Ids start with
 * `yoga_` and are permanent: progress and other features refer to them.
 */

/** In the order the tree draws them; the short lanes first, so the phone's lane bar breaks after Twists. */
export const YOGA_LANES = ['Standing', 'Folds', 'Hips', 'Twists', 'Backbends', 'Arm Balances', 'Inversions'] as const;
export type YogaLane = (typeof YOGA_LANES)[number];

export const TOP_LEVEL = 9;

const BANDS: LevelBand[] = [
  { id: 'beginner', label: 'Beginner · 1–3', min: 1, max: 3 },
  { id: 'intermediate', label: 'Intermediate · 4–6', min: 4, max: 6 },
  { id: 'advanced', label: 'Advanced · 7–9', min: 7, max: TOP_LEVEL },
  { id: 'all', label: 'All levels', min: 1, max: TOP_LEVEL },
];

const RANKS: Rank[] = [
  { min: 0, title: 'Mat Novice' },
  { min: 5, title: 'Steady Breath' },
  { min: 14, title: 'Rooted' },
  { min: 26, title: 'Supple Warrior' },
  { min: 40, title: 'Balance Keeper' },
  { min: 56, title: 'Inversion Adept' },
  { min: 72, title: 'Yoga Sage' },
];

export const YOGA_RULES: TreeRules = { lanes: [...YOGA_LANES], bands: BANDS, ranks: RANKS };

interface PoseInput {
  id: string;
  /** The English name people use in class. */
  name: string;
  /** The Sanskrit name, where one is standard. */
  sanskrit?: string;
  level: number;
  lane: YogaLane;
  line: string;
  after?: string[];
  summary: string;
  /** Starts with the hold time ("30 s …"), so the test can time it. */
  masteredWhen: string;
  steps: string[];
  tip?: string;
  /** Who should take care, and how. */
  caution?: string;
  /** What it works, shown as tags. */
  trains: string[];
  /** The hero's attributes it builds; left out where none clearly fits. */
  builds?: TrainableAttribute[];
  /** Held once on each side. */
  sides?: boolean;
  /** Search words for a tutorial when the name alone is ambiguous. */
  search?: string;
}

export interface YogaPose extends CatalogSkill {
  lane: YogaLane;
  builds: TrainableAttribute[];
  sides: boolean;
  /** The standard's hold, in seconds. */
  seconds: number;
}

/** The hold a standard opens with: "30 s each side…" is 30. */
const holdOf = (text: string) => Number(/^(\d+)\s*s\b/.exec(text)?.[1] ?? 30);

const pose = (input: PoseInput): YogaPose => ({
  id: input.id,
  name: input.name,
  ...(input.sanskrit ? { otherName: input.sanskrit } : {}),
  level: input.level,
  levelLabel: `Level ${input.level}`,
  lane: input.lane,
  focus: listOf(input.trains),
  subCategory: input.line,
  swimlane: input.lane,
  prerequisites: input.after ?? [],
  summary: input.summary,
  unlockRequirements: input.masteredWhen,
  description: input.steps,
  expertTip: input.tip,
  ...(input.caution ? { caution: input.caution } : {}),
  musclesTargeted: input.trains,
  youtubeQuery: `${input.search ?? input.name} yoga pose tutorial`,
  builds: input.builds ?? [],
  sides: Boolean(input.sides),
  seconds: holdOf(input.masteredWhen),
  // The campaign XP mastering it pays, as evidence.ts counts it.
  xpReward: input.level * 40,
});

