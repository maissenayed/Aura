import { CatalogSkill, LevelBand, Rank, TreeRules, listOf } from '../utils/skillTree';

/**
 * The bouldering skill tree: technique, body positions, movement, and grip and
 * strength skills, each placed on the V-grade where it starts to matter.
 *
 * `level` is the V-grade number (0 = V0 … 10 = V10 and harder); `grade`,
 * `font` and `levelLabel` spell it out. Prerequisites point at skills of an
 * easier grade. Ids start with `bld_` and are permanent: progress and other
 * features refer to them.
 */

export const BOULDERING_LANES = ['Technique', 'Body', 'Movement', 'Strength'] as const;
export type BoulderingLane = (typeof BOULDERING_LANES)[number];

/** Highest grade on the tree; it stands for "this grade and harder". */
export const TOP_GRADE = 10;

/** The usual Fontainebleau equivalent of each V-grade (the upper end where a V-grade spans two). */
const FONT_GRADES = ['4', '5', '5+', '6A+', '6B+', '6C+', '7A', '7A+', '7B+', '7C', '7C+'];

export function vGrade(level: number): string {
  return level >= TOP_GRADE ? `V${TOP_GRADE}+` : `V${level}`;
}

export function fontGrade(level: number): string {
  return FONT_GRADES[Math.max(0, Math.min(FONT_GRADES.length - 1, level))];
}

const BANDS: LevelBand[] = [
  { id: 'beginner', label: 'Beginner · V0–V2', min: 0, max: 2 },
  { id: 'intermediate', label: 'Intermediate · V3–V5', min: 3, max: 5 },
  { id: 'advanced', label: 'Advanced · V6–V8', min: 6, max: 8 },
  { id: 'elite', label: 'Elite · V9–V10+', min: 9, max: TOP_GRADE },
  { id: 'all', label: 'All grades', min: 0, max: TOP_GRADE },
];

const RANKS: Rank[] = [
  { min: 0, title: 'Pad Carrier' },
  { min: 5, title: 'Problem Solver' },
  { min: 14, title: 'Crux Hunter' },
  { min: 26, title: 'Project Crusher' },
  { min: 40, title: 'Boulder Sage' },
];

export const BOULDERING_RULES: TreeRules = { lanes: [...BOULDERING_LANES], bands: BANDS, ranks: RANKS };

interface SkillInput {
  id: string;
  name: string;
  grade: number;
  lane: BoulderingLane;
  line: string;
  after?: string[];
  summary: string;
  masteredWhen: string;
  steps: string[];
  tip?: string;
  trains: string[];
  /** Search words for a tutorial when the name alone is ambiguous. */
  search?: string;
}

export interface BoulderingSkill extends CatalogSkill {
  lane: BoulderingLane;
  /** "V4", or "V10+" at the top. */
  grade: string;
  /** The Font equivalent, e.g. "6B+". */
  font: string;
}

const skill = (input: SkillInput): BoulderingSkill => ({
  id: input.id,
  name: input.name,
  level: input.grade,
  grade: vGrade(input.grade),
  font: fontGrade(input.grade),
  levelLabel: `${vGrade(input.grade)} · ${fontGrade(input.grade)}`,
  lane: input.lane,
  focus: listOf(input.trains),
  subCategory: input.line,
  swimlane: input.lane,
  prerequisites: input.after ?? [],
  summary: input.summary,
  unlockRequirements: input.masteredWhen,
  description: input.steps,
  expertTip: input.tip,
  musclesTargeted: input.trains,
  youtubeQuery: `${input.search ?? input.name} bouldering technique`,
  xpReward: (input.grade + 1) * 150,
});

